"""
Tables and figure for the block-permutation-null experiment.

Reads ``results/block_permutation_null/{langevin_block_null,toy_block_null,
langevin_block_vmeasure}.csv`` and writes the tables quoted in FINDINGS.md plus
``figures/block_null_alignment.{pdf,png}``.

Usage
-----
    python mfpy/experiments/analyze_block_permutation_null.py
"""

from __future__ import annotations

import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RESULT_DIR = os.path.join(REPO_ROOT, "results", "block_permutation_null")
TABLE_DIR = os.path.join(RESULT_DIR, "tables")
FIG_DIR = os.path.join(RESULT_DIR, "figures")

FIXED_N_SEGMENTS = 157  # manuscript fixed-quantile baseline, w=215, q=0.86


def save(df, name):
    os.makedirs(TABLE_DIR, exist_ok=True)
    df.to_csv(os.path.join(TABLE_DIR, f"{name}.csv"), index=False)
    with open(os.path.join(TABLE_DIR, f"{name}.md"), "w") as fh:
        fh.write(df.to_markdown(index=False))
    print(f"\n== {name} ==")
    print(df.to_string(index=False))


def main():
    lang = pd.read_csv(os.path.join(RESULT_DIR, "langevin_block_null.csv"))
    toy = pd.read_csv(os.path.join(RESULT_DIR, "toy_block_null.csv"))
    vm = pd.read_csv(os.path.join(RESULT_DIR, "langevin_block_vmeasure.csv"))

    t1 = lang[lang.scheme.isin(["-", "full_shuffle", "circular"])][
        ["method", "scheme", "block_length", "cutoff", "cutoff_obs_quantile",
         "n_segments"]
    ].round(4)
    save(t1, "table1_langevin_alignment")

    # scheme robustness: circular vs moving at matched L
    piv = lang[lang.scheme.isin(["circular", "moving"])].pivot_table(
        index="block_length", columns="scheme",
        values=["cutoff_obs_quantile", "n_segments"]
    ).round(4)
    save(piv.reset_index(), "table2_scheme_robustness")

    t3 = (
        toy.groupby(["method", "block_length"], dropna=False)
        .agg(
            f1_tau10=("f1_tau10", "mean"),
            precision=("precision_tau10", "mean"),
            recall=("recall_tau10", "mean"),
            n_predicted_cps=("n_predicted_cps", "mean"),
            median_abs_error=("median_abs_error", "mean"),
        )
        .round(3)
        .reset_index()
    )
    save(t3, "table3_toy_by_block_length")

    t4 = vm[vm.core == 0.0][
        ["method", "block_length", "n_segments", "adp_k", "adp_v2", "adp_v3"]
    ].round(4)
    save(t4, "table4_langevin_vmeasure")

    # ---------------------------------------------------------------- figure
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    circ = lang[lang.scheme == "circular"].sort_values("block_length")
    fixed = lang[lang.method == "fixed_quantile"].iloc[0]

    fig, axes = plt.subplots(1, 3, figsize=(13, 4))

    ax = axes[0]
    ax.semilogx(circ.block_length, circ.cutoff_obs_quantile, "o-", label="block null")
    ax.axhline(fixed.cutoff_obs_quantile, ls="--", color="k",
               label=f"fixed quantile (q={fixed.q})")
    ax.axvspan(50, 75, color="tab:green", alpha=0.15, label=r"within-well $\tau_{int}$")
    ax.set_xlabel("block length L")
    ax.set_ylabel("cutoff, as a quantile of the observed statistic")
    ax.set_title("Langevin: where the null cutoff lands")
    ax.legend(fontsize=8)

    ax = axes[1]
    ax.semilogx(circ.block_length, circ.n_segments, "o-")
    ax.axhline(FIXED_N_SEGMENTS, ls="--", color="k", label="fixed quantile (157)")
    ax.axvspan(50, 75, color="tab:green", alpha=0.15)
    ax.set_xlabel("block length L")
    ax.set_ylabel("segments")
    ax.set_title("Langevin: segmentation")
    ax.legend(fontsize=8)

    ax = axes[2]
    sub = toy[toy.method == "block_pointwise"].groupby("block_length")["f1_tau10"].mean()
    ax.semilogx(sub.index, sub.values, "o-", label="block null")
    base = toy[toy.method == "fixed_quantile"]["f1_tau10"].mean()
    shuf = toy[toy.method == "resample_pointwise"]["f1_tau10"].mean()
    ax.axhline(base, ls="--", color="k", label="fixed quantile (q=0.95)")
    ax.axhline(shuf, ls=":", color="tab:red", label="full shuffle")
    ax.set_xlabel("block length L")
    ax.set_ylabel(r"mean $F_1$ ($\tau=10$)")
    ax.set_title("Toy: detection")
    ax.legend(fontsize=8)

    fig.suptitle(
        "Block-permutation null vs. block length"
        "—generated by `analyze_block_permutation_null.py`", fontsize=10
    )
    fig.tight_layout()
    os.makedirs(FIG_DIR, exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(FIG_DIR, f"block_null_alignment.{ext}"), dpi=150)
    print(f"\nwrote {FIG_DIR}/block_null_alignment.{{pdf,png}}")


if __name__ == "__main__":
    main()
