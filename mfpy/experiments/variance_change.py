"""
Changes in variance, not just in mean (reviewer comment 3(a)).

Why this exists
---------------
The shipped toy set is generated by ``data/Toy_Model_Trajectories/Trajectory_Generator.m``,
which draws both metastable states with ``laprnd(n, 1, mean, sigma)`` using the *same*
``sigma``. Every change point in every trajectory tested so far is therefore a pure shift in
the mean. That is precisely the case a mean-based (CUSUM-type) statistic already handles,
and it leaves the paper's central claim -- that a Wasserstein statistic detects general
distributional change without parametric assumptions -- untested on the setting that would
actually demonstrate it.

The reviewer asked for "(instantaneous) changes in: mean and/or covariance". This module
generates all three change types, at instantaneous and gradual transitions, and scores the
Wasserstein statistic against a mean-based comparator on identical data.

Design
------
Both states are Laplace. For location-scale families the 2-Wasserstein geodesic is the
linear interpolation of quantile functions, so a Laplace-to-Laplace transition interpolates
the location and the scale linearly and stays Laplace throughout -- the same construction
the manuscript describes, extended to let the scale move too.

For Laplace(mu, b), the standard quantile function has second moment 2, so

    W2^2( Laplace(mu1,b1), Laplace(mu2,b2) ) = (mu1-mu2)^2 + 2 (b1-b2)^2.

That identity is what makes the three arms comparable: each is parameterised by the *same*
state separation ``d = W2(A, B)``, and the separation is split differently between location
and scale.

    ``mean``      mu_B - mu_A = d,          b_B = b_A
    ``variance``  mu_B = mu_A,              b_B - b_A = d / sqrt(2)
    ``both``      mu_B - mu_A = d/sqrt(2),  b_B - b_A = d / 2

So a horizontal comparison across arms at fixed ``d`` holds the distance between the two
state laws constant, and any difference in detectability is attributable to *where* the
change lives rather than to how large it is.

Comparator
----------
``w2``    the manuscript's statistic: W2 between the empirical laws of the two half-windows.
``mean``  the same sliding window, but ``|mean(right) - mean(left)|`` -- a moving-window
          CUSUM-type statistic. It is structurally blind to a change that leaves the mean
          fixed.

Everything downstream is shared: the same thresholding, the same run detection, the same
gradient boundary rule, the same Hungarian scoring. Only the statistic differs, so the
comparison is controlled.

Replicates
----------
Every cell is run with ``--reps`` independent realisations (default 10), which also supplies
the error bars missing elsewhere in the revision (reviewer comment 3).

Usage
-----
    python -m mfpy.experiments.variance_change --reps 10
    python -m mfpy.experiments.variance_change --reps 2 --smoke
"""

from __future__ import annotations

import argparse
import os
import shutil
import sys
import time

import numpy as np
import pandas as pd

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from mfpy.experiments import boundary_estimators as be  # noqa: E402
from mfpy.experiments.toy_scoring import match_change_points  # noqa: E402
from mfpy.experiments.toy_sweep import fast_metric_derivative_1d  # noqa: E402

RESULT_DIR = os.path.join(REPO_ROOT, "results", "variance_change")

# Trajectory shape, chosen to match the shipped toy set: 20 stable blocks, 19 transitions.
N_BLOCKS = 20
BLOCK_LEN = 250

BASE_MU = 100.0
BASE_B = 20.0  # Laplace scale of state A; variance is 2 b^2

KINDS = ("mean", "variance", "both")
SEPARATIONS = (5.0, 10.0, 20.0, 40.0, 80.0)  # d = W2 between the two state laws
TRANSITION_LENGTHS = (0, 10, 25, 50)  # 0 = instantaneous
QUANTILES = (0.50, 0.60, 0.70, 0.75, 0.80, 0.85, 0.90, 0.925, 0.95, 0.975, 0.99)
TAUS = (5, 10, 25)
DETECTORS = ("w2", "mean")
EXTRACTORS = ("gradient", "peak")
# A scale change should need more samples per half-window to resolve than a location
# change does, so the window is swept rather than fixed at the manuscript's 25.
WINDOWS = (25, 50, 100)

# Laplace(0,1) has quantile function with second moment 2; see module docstring.
_LAPLACE_Q2 = 2.0


def state_parameters(kind, d, base_mu=BASE_MU, base_b=BASE_B):
    """
    (mu_A, b_A, mu_B, b_B) for a given change type and state separation ``d = W2(A,B)``.

    Verified by ``w2_laplace`` below: every arm returns exactly ``d``.
    """
    if kind == "mean":
        return base_mu, base_b, base_mu + d, base_b
    if kind == "variance":
        return base_mu, base_b, base_mu, base_b + d / np.sqrt(_LAPLACE_Q2)
    if kind == "both":
        # split the squared separation evenly between the location and scale terms
        d_mu = d / np.sqrt(2.0)
        d_b = np.sqrt(d**2 / 2.0 / _LAPLACE_Q2)
        return base_mu, base_b, base_mu + d_mu, base_b + d_b
    raise ValueError(f"unknown kind: {kind}")


def w2_laplace(mu1, b1, mu2, b2):
    """Exact W2 between two Laplace laws."""
    return float(np.sqrt((mu1 - mu2) ** 2 + _LAPLACE_Q2 * (b1 - b2) ** 2))


def generate(kind, d, tl, rng, n_blocks=N_BLOCKS, block_len=BLOCK_LEN):
    """
    Build a trajectory alternating between two Laplace states.

    Returns ``(x, change_points)``. A transition of length ``tl`` occupies ``tl`` samples
    drawn from the Wasserstein interpolant and contributes **two** change points, its start
    and its end; an instantaneous change (``tl = 0``) contributes **one**.
    """
    mu_a, b_a, mu_b, b_b = state_parameters(kind, d)

    pieces, cps, cursor = [], [], 0
    for i in range(n_blocks):
        mu, b = (mu_a, b_a) if i % 2 == 0 else (mu_b, b_b)
        pieces.append(rng.laplace(mu, b, block_len))
        cursor += block_len

        if i == n_blocks - 1:
            break

        if tl == 0:
            cps.append(cursor)
            continue

        # McCann interpolant: location and scale both move linearly, law stays Laplace.
        lam = (np.arange(tl) + 1.0) / (tl + 1.0)
        src = (mu, b)
        dst = (mu_b, b_b) if i % 2 == 0 else (mu_a, b_a)
        mus = (1 - lam) * src[0] + lam * dst[0]
        bs = (1 - lam) * src[1] + lam * dst[1]
        pieces.append(rng.laplace(mus, bs))
        cps.extend([cursor, cursor + tl])
        cursor += tl

    return np.concatenate(pieces), np.array(sorted(cps), dtype=int)


def mean_statistic(x, w):
    """
    Moving-window CUSUM-type statistic: |mean(right half) - mean(left half)|.

    Deliberately the same sliding-window architecture as the Wasserstein statistic, so the
    two differ only in what they measure.
    """
    from numpy.lib.stride_tricks import sliding_window_view

    T = x.shape[0]
    out = np.zeros(T)
    if T < 2 * w:
        return out
    win = sliding_window_view(x, 2 * w)
    vals = np.abs(win[:, w:].mean(axis=1) - win[:, :w].mean(axis=1))
    out[w : T - w] = vals[: T - 2 * w]
    return out


def statistic(name, x, w):
    if name == "w2":
        return fast_metric_derivative_1d(x, w)
    if name == "mean":
        return mean_statistic(x, w)
    raise ValueError(f"unknown detector: {name}")


def identify_peak(stat, q):
    """
    One change point per supra-threshold run, at the run's peak.

    The manuscript's ``gradient`` rule emits *two* boundaries per run, which is correct for
    a gradual transition (a ramp has a start and an end) but structurally wrong for an
    instantaneous change, where there is only one change point to find. Against 19 true
    change points it emits ~38 predictions, capping precision near 0.5 and F1 near 0.67
    regardless of how well the change is localised.

    This variant collapses each run to the single index at which the statistic is largest.
    It is used for the instantaneous arm so the comparison is not dominated by that
    artefact; both extractors are recorded for every cell so the effect can be read off.
    """
    stat = np.asarray(stat).ravel()
    changes = []
    for start, end in be.find_runs(stat, q):
        if end > start:
            changes.append(start + int(np.argmax(stat[start:end])))
    return np.sort(np.unique(np.array(changes, dtype=int)))


def extract(name, stat, q):
    if name == "gradient":
        return be.identify_change_points(stat, q, estimator="gradient")
    if name == "peak":
        return identify_peak(stat, q)
    raise ValueError(f"unknown extractor: {name}")


def score(predicted, truth, tau, T):
    """Precision / recall / F1 under one-to-one Hungarian matching within ``tau``."""
    predicted = np.asarray([p for p in np.asarray(predicted).ravel() if 0 < p < T - 1])
    pairs = match_change_points(predicted, truth, tau)
    tp = len(pairs)
    precision = tp / len(predicted) if len(predicted) else 0.0
    recall = tp / len(truth) if len(truth) else 0.0
    f1 = 0.0 if precision + recall == 0 else 2 * precision * recall / (precision + recall)
    if tp:
        err = np.abs(predicted[pairs[:, 0]] - truth[pairs[:, 1]])
        median_abs_error = float(np.median(err))
    else:
        median_abs_error = np.nan
    return precision, recall, f1, median_abs_error


def run(reps, windows, kinds, separations, tls, seed, start=0, stop=None):
    cells = [(k, d, tl) for k in kinds for d in separations for tl in tls]
    cells = cells[start:stop]

    rows, t0 = [], time.time()
    for n, (kind, d, tl) in enumerate(cells, 1):
        mu_a, b_a, mu_b, b_b = state_parameters(kind, d)
        for rep in range(reps):
            rng = np.random.default_rng(
                seed + hash((kind, int(d * 100), tl, rep)) % (2**31)
            )
            x, truth = generate(kind, d, tl, rng)
            T = x.shape[0]

            for w in windows:
              for det in DETECTORS:
                stat = statistic(det, x, w)
                for extractor in EXTRACTORS:
                    for q in QUANTILES:
                        cps = extract(extractor, stat, q)
                        p, r, f1, mae = score(cps, truth, 10, T)
                        row = {
                            "kind": kind,
                            "extractor": extractor,
                            "separation": d,
                            "transition_length": tl,
                            "rep": rep,
                            "detector": det,
                            "q": q,
                            "w": w,
                            "mu_A": mu_a, "b_A": b_a, "mu_B": mu_b, "b_B": b_b,
                            "w2_states": w2_laplace(mu_a, b_a, mu_b, b_b),
                            "n_true_cps": len(truth),
                            "n_predicted_cps": len(cps),
                            "precision_tau10": p,
                            "recall_tau10": r,
                            "f1_tau10": f1,
                            "median_abs_error": mae,
                        }
                        for tau in TAUS:
                            if tau != 10:
                                row[f"f1_tau{tau}"] = score(cps, truth, tau, T)[2]
                        rows.append(row)
        if n % 5 == 0:
            print(f"[{n}/{len(cells)}] {time.time() - t0:.0f}s", flush=True)
    return pd.DataFrame(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reps", type=int, default=10)
    ap.add_argument("--windows", nargs="+", type=int, default=list(WINDOWS))
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--start", type=int, default=0)
    ap.add_argument("--stop", type=int, default=None)
    ap.add_argument("--smoke", action="store_true")
    ap.add_argument("--suffix", default="")
    ap.add_argument("--out", default=RESULT_DIR)
    args = ap.parse_args()

    kinds = KINDS
    seps = (10.0, 40.0) if args.smoke else SEPARATIONS
    tls = (0, 25) if args.smoke else TRANSITION_LENGTHS

    os.makedirs(args.out, exist_ok=True)
    tmp = "/tmp/varchange"
    os.makedirs(tmp, exist_ok=True)

    df = run(
        args.reps, args.windows, kinds, seps, tls, args.seed, args.start, args.stop
    )
    name = f"variance_change{args.suffix}.csv"
    local = os.path.join(tmp, name)
    df.to_csv(local, index=False)
    shutil.copy(local, os.path.join(args.out, name))
    print(f"{name}: {len(df)} rows")


if __name__ == "__main__":
    main()
