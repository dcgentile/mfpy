"""
Explanatory figures for the block-resampling memo.

Three figures, all built from the Langevin trajectory so that nothing in them is
schematic-only:

``fig_construction``
    How a circular block bootstrap replicate is assembled, and what it preserves. Top:
    a stretch of the real series. Middle: a full shuffle (L = 1) of the same values.
    Bottom: a circular block resample at L = 51. All three have identical marginal
    distributions; only the temporal structure differs. The inset shows the
    autocorrelation function of each.

``fig_null_shift``
    Why that matters for the threshold. The distribution of the windowed Wasserstein
    statistic on the real series, against the pooled null distribution under each
    resampling scheme, with the resulting q = 0.5 cutoffs marked. Shows the full-shuffle
    null collapsing to the left of the observed distribution and the block null landing
    on top of the fixed-quantile cutoff.

``fig_block_tradeoff``
    The two failure modes bounding the choice of L, drawn on the series itself: blocks
    shorter than the within-state correlation time break dependence that the null should
    keep; blocks longer than the dwell time carry whole metastable states, so the "no
    change" null contains changes.

Usage
-----
    python mfpy/experiments/block_bootstrap_diagram.py
"""

from __future__ import annotations

import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, REPO_ROOT)
sys.path.insert(0, HERE)

from toy_sweep import fast_metric_derivative_1d  # noqa: E402
from block_permutation_null import block_permutation, block_null_pooled  # noqa: E402
from resampling_threshold import null_distributions  # noqa: E402

FIG_DIR = os.path.join(REPO_ROOT, "results", "auto_block_null", "figures")
LANGEVIN = os.path.join(REPO_ROOT, "data", "Langevin", "langevin.txt")
W, Q, Q_NULL, L_AUTO = 215, 0.86, 0.5, 51


def acf(x, max_lag=400):
    x = np.asarray(x, float) - np.mean(x)
    n = 1 << (2 * len(x) - 1).bit_length()
    f = np.fft.rfft(x, n)
    a = np.fft.irfft(f * np.conj(f), n)[: max_lag + 1].real
    return a / a[0]


def save(fig, name):
    os.makedirs(FIG_DIR, exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(FIG_DIR, f"{name}.{ext}"), dpi=150,
                    bbox_inches="tight")
    print(f"wrote {FIG_DIR}/{name}.{{pdf,png}}")


def main():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    X = np.loadtxt(LANGEVIN).ravel()
    rng = np.random.default_rng(0)

    # ---------------------------------------------------------- construction
    seg = X[:6000]
    shuffled = block_permutation(seg, 1, rng)
    blocked = block_permutation(seg, L_AUTO, rng)

    fig, axes = plt.subplots(3, 2, figsize=(13, 6.5),
                             gridspec_kw={"width_ratios": [3, 1]})
    rows = [("observed series", seg, "tab:blue"),
            (r"full shuffle  ($L=1$)", shuffled, "tab:red"),
            (rf"circular block resample  ($L={L_AUTO}$)", blocked, "tab:green")]
    for (title, y, c), (ax, axr) in zip(rows, axes):
        ax.plot(y, lw=0.4, color=c)
        ax.set_title(title, fontsize=9, loc="left")
        ax.set_ylabel("x")
        ax.set_ylim(-2, 2)
        axr.plot(acf(y, 400), lw=1.2, color=c)
        axr.axhline(0, color="k", lw=0.5)
        axr.set_ylim(-0.3, 1.05)
        axr.set_title("autocorrelation", fontsize=8, loc="left")
    axes[-1][0].set_xlabel("time step")
    axes[-1][1].set_xlabel("lag")
    fig.suptitle(
        "Building a null replicate: identical marginals, different temporal structure"
        "—generated by `block_bootstrap_diagram.py`", fontsize=10)
    fig.tight_layout()
    save(fig, "fig_construction")
    plt.close(fig)

    # ------------------------------------------------------------ null shift
    T = X.shape[0]
    g = fast_metric_derivative_1d(X, W)
    obs = g[W : T - W]
    _, pooled_shuffle = null_distributions(X, W, 15, np.random.default_rng(0))
    pooled_block = block_null_pooled(X, W, 15, np.random.default_rng(0), L_AUTO)

    cut_fixed = float(np.quantile(g, Q))
    cut_shuffle = float(np.quantile(pooled_shuffle, Q_NULL))
    cut_block = float(np.quantile(pooled_block, Q_NULL))

    fig, ax = plt.subplots(figsize=(10, 4.2))
    bins = np.linspace(0, max(obs.max(), 1.2), 160)
    ax.hist(obs, bins=bins, density=True, alpha=0.45, color="tab:blue",
            label="observed statistic")
    ax.hist(pooled_shuffle, bins=bins, density=True, alpha=0.45, color="tab:red",
            label=r"null, full shuffle ($L=1$)")
    ax.hist(pooled_block, bins=bins, density=True, alpha=0.45, color="tab:green",
            label=rf"null, block ($L={L_AUTO}$)")
    top = ax.get_ylim()[1]
    for cut, col, lab, frac in ((cut_shuffle, "tab:red", "shuffle cutoff", 0.95),
                                (cut_block, "tab:green", "block cutoff", 0.80),
                                (cut_fixed, "k", f"fixed quantile q={Q}", 0.62)):
        ax.axvline(cut, color=col, ls="--", lw=1.6)
        ax.annotate(f"{lab}\n{cut:.3f}", xy=(cut, top * frac),
                    xytext=(cut + 0.06, top * frac), fontsize=8, color=col,
                    va="top", ha="left")
    ax.set_xlabel(r"windowed Wasserstein statistic  $\dot\gamma$")
    ax.set_ylabel("density")
    ax.legend(fontsize=8, loc="upper right")
    ax.set_title(
        "Where each rule puts the cutoff (Langevin, w=215). Note the block null is "
        "shifted *right* of\nthe observed statistic — see FINDINGS §block-join bias"
        "—generated by `block_bootstrap_diagram.py`", fontsize=9)
    fig.tight_layout()
    save(fig, "fig_null_shift")
    plt.close(fig)

    # -------------------------------------------------------- block tradeoff
    fig, axes = plt.subplots(3, 1, figsize=(11, 5.5), sharex=True, sharey=True)
    show = X[:6000]
    for ax, L, note in (
        (axes[0], 5, "too short: within-state dependence destroyed, "
                     "null collapses, oversegmentation"),
        (axes[1], L_AUTO, "about right: dependence kept, states still broken up"),
        (axes[2], 2000, "too long: whole metastable states survive, "
                        "the 'no change' null contains changes"),
    ):
        y = block_permutation(show, L, np.random.default_rng(3))
        ax.plot(y, lw=0.4, color="tab:purple")
        ax.set_ylim(-2, 2)
        ax.set_ylabel("x")
        ax.set_title(rf"$L={L}$ — {note}", fontsize=9, loc="left")
    axes[-1].set_xlabel("time step")
    fig.suptitle(
        "Block length is bounded below by the within-state correlation time "
        "and above by the dwell time"
        "—generated by `block_bootstrap_diagram.py`", fontsize=10)
    fig.tight_layout()
    save(fig, "fig_block_tradeoff")
    plt.close(fig)


if __name__ == "__main__":
    main()
