"""
Fully automatic pipeline on toy, Langevin and Prinz: clusterings and figures.

Runs three threshold rules end to end on each dataset and saves what each one actually
produced -- segments, per-point cluster labels, cluster composition, and a plot:

``fixed``     the manuscript's fixed quantile of the observed statistic at (w, q)
``shuffle``   the published pointwise permutation null (full shuffle), q_null = 0.5
``auto``      the block null with L chosen automatically by ``auto_block_length``

Nothing here is hand-tuned per dataset except `(w, q)`, which are the manuscript's own
per-dataset settings and are used identically by all three rules.

Datasets
--------
toy      four representative trajectories from ``data/Toy_Model_Trajectories``, w = 25,
         q = 0.95, ground truth available
langevin ``data/Langevin/langevin.txt``, w = 215, q = 0.86, core-set proxy truth
prinz    ``data/prinz/prinz.txt``, w = 16, q = 0.5, four-well potential, no truth.
         NOTE this file is regenerated by ``make_prinz_data.py`` -- the original
         referenced by ``Notebooks/Prinz/prinz-figs.ipynb`` is not in the repo.

Usage
-----
    python mfpy/experiments/auto_pipeline_clusterings.py [--R 30] [--datasets toy prinz]
"""

from __future__ import annotations

import argparse
import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, REPO_ROOT)
sys.path.insert(0, HERE)

import boundary_estimators as be  # noqa: E402
from toy_sweep import fast_metric_derivative_1d  # noqa: E402
from toy_scoring import load_ground_truth  # noqa: E402
from resampling_threshold import (  # noqa: E402
    identify_change_points_cutoff,
    null_distributions,
)
from block_permutation_null import block_null_pooled  # noqa: E402
from auto_block_length import estimate_block_length  # noqa: E402
from vmeasure import (  # noqa: E402
    _adp_labels,
    _pairwise_segment_distances,
    langevin_point_labels,
    toy_point_labels,
    score,
    TRANSITION,
)

RESULT_DIR = os.path.join(REPO_ROOT, "results", "auto_block_null")
Q_NULL = 0.5

TOY_CASES = [(5, 6), (5, 48), (20, 48), (20, 95)]
TOY_W, TOY_Q = 25, 0.95
LANG_W, LANG_Q = 215, 0.86
PRINZ_W, PRINZ_Q = 16, 0.5


def cluster_from_changes(X, changes, Z=1.65):
    D = _pairwise_segment_distances(X, changes)
    segment_labels, n_distinct = _adp_labels(D, Z=Z)
    point_labels = np.empty(X.shape[0], dtype=int)
    for i in range(len(changes) - 1):
        point_labels[changes[i] : changes[i + 1]] = segment_labels[i]
    return point_labels, n_distinct


def run_rules(X, w, q, R, seed=0):
    """Return {rule: (changes, cutoff, L, info)} for the three threshold rules."""
    T = X.shape[0]
    gammadot = fast_metric_derivative_1d(X, w)
    out = {}

    cut = float(np.quantile(gammadot, q))
    ch = be.identify_change_points(gammadot, q, estimator="gradient")
    out["fixed"] = (np.unique(np.append(ch, T)), cut, None, {})

    _, pooled = null_distributions(X, w, R, np.random.default_rng(seed))
    cut = float(np.quantile(pooled, Q_NULL))
    out["shuffle"] = (
        np.unique(np.append(
            identify_change_points_cutoff(gammadot, cut, estimator="gradient"), T)),
        cut, 1, {},
    )

    L, info, _, _ = estimate_block_length(X, w, q, verbose=False)
    pooled = block_null_pooled(X, w, R, np.random.default_rng(seed), L,
                               scheme="circular")
    cut = float(np.quantile(pooled, Q_NULL))
    out["auto"] = (
        np.unique(np.append(
            identify_change_points_cutoff(gammadot, cut, estimator="gradient"), T)),
        cut, L, info,
    )
    return out, gammadot


def composition(X, pred, changes, core=None):
    """Point-weighted cluster composition. ``core`` marks the between-state band."""
    rows = []
    seg_cluster = np.array([pred[int(a)] for a in changes[:-1]])
    for c in np.unique(pred):
        m = pred == c
        row = {
            "cluster": int(c),
            "n_segments": int((seg_cluster == c).sum()),
            "n_points": int(m.sum()),
            "mean_x": float(X[m].mean()),
            "std_x": float(X[m].std()),
        }
        if core is not None:
            row["frac_core"] = float(core[m].mean())
        rows.append(row)
    return pd.DataFrame(rows).sort_values("mean_x")


def process(name, X, w, q, R, truth=None, core=None, plot_range=None, seed=0):
    print(f"\n=== {name}: T={X.shape[0]}, w={w}, q={q} ===", flush=True)
    rules, _ = run_rules(X, w, q, R, seed=seed)

    os.makedirs(os.path.join(RESULT_DIR, "clusterings"), exist_ok=True)
    panels, summary, comps = [], [], []
    for rule, (changes, cutoff, L, info) in rules.items():
        pred, n_distinct = cluster_from_changes(X, changes)
        comp = composition(X, pred, changes, core=core)
        comp.insert(0, "rule", rule)
        comp.insert(0, "dataset", name)
        comps.append(comp)

        rec = {
            "dataset": name, "rule": rule, "w": w, "q": q,
            "block_length": L, "cutoff": cutoff,
            "n_segments": int(len(changes) - 1), "k": int(len(np.unique(pred))),
            "tau_within": info.get("tau_within_median", np.nan),
            "tau_global": info.get("tau_global", np.nan),
        }
        if truth is not None:
            rec["v3"] = score(truth, pred)[2]
            keep = truth != TRANSITION
            rec["v2"] = score(truth[keep], pred[keep])[2]
        summary.append(rec)

        tag = f"{name}_{rule}"
        pd.DataFrame({
            "start": changes[:-1].astype(int), "end": changes[1:].astype(int),
            "cluster": [int(pred[int(a)]) for a in changes[:-1]],
        }).to_csv(os.path.join(RESULT_DIR, "clusterings",
                               f"segments_{tag}.csv"), index=False)
        np.save(os.path.join(RESULT_DIR, "clusterings", f"labels_{tag}.npy"), pred)
        panels.append((rule, pred, changes, rec))
        print(f"  {rule:>8}: L={L} cutoff={cutoff:.4f} "
              f"{rec['n_segments']} segments, k={rec['k']}"
              + (f", V2={rec['v2']:.3f}" if truth is not None else ""), flush=True)

    return panels, summary, pd.concat(comps, ignore_index=True)


def plot_dataset(name, X, panels, lo, hi, outdir):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    colors = np.array(["tab:blue", "tab:orange", "tab:green", "tab:red",
                       "tab:purple", "tab:brown", "tab:pink", "tab:olive"])
    fig, axes = plt.subplots(len(panels), 1, figsize=(12, 2.2 * len(panels)),
                             sharex=True, sharey=True)
    for ax, (rule, pred, changes, rec) in zip(np.atleast_1d(axes), panels):
        sl = slice(lo, hi)
        ax.scatter(np.arange(lo, hi), X[sl], c=colors[pred[sl] % len(colors)],
                   s=1.2, linewidths=0)
        for ch in changes[(changes >= lo) & (changes < hi)]:
            ax.axvline(ch, color="k", lw=0.25, alpha=0.3)
        title = (f"{rule}: L={rec['block_length']}, {rec['n_segments']} segments, "
                 f"k={rec['k']}")
        if "v2" in rec and rec["v2"] == rec["v2"]:
            title += f", V2={rec['v2']:.3f}"
        ax.set_title(title, fontsize=9, loc="left")
        ax.set_ylabel("x")
    np.atleast_1d(axes)[-1].set_xlabel(
        f"time step (showing {lo}–{hi} of {X.shape[0]})")
    fig.suptitle(f"{name}: clustering under each threshold rule"
                 "—generated by `auto_pipeline_clusterings.py`", fontsize=10)
    fig.tight_layout()
    os.makedirs(outdir, exist_ok=True)
    for ext in ("pdf", "png"):
        fig.savefig(os.path.join(outdir, f"clustering_{name}.{ext}"), dpi=150)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--R", type=int, default=30)
    ap.add_argument("--datasets", nargs="+",
                    default=["toy", "langevin", "prinz"])
    args = ap.parse_args()

    os.makedirs(RESULT_DIR, exist_ok=True)
    figdir = os.path.join(RESULT_DIR, "figures")
    all_summary, all_comp = [], []

    if "toy" in args.datasets:
        base = os.path.join(REPO_ROOT, "data", "Toy_Model_Trajectories")
        for sigma, tl in TOY_CASES:
            p = os.path.join(base, f"sigma_{sigma}_transition_{tl}.txt")
            if not os.path.exists(p):
                print(f"skip missing {p}")
                continue
            X = np.loadtxt(p).ravel()
            ramps = load_ground_truth(p.replace(".txt", "_GroundTruth.txt"),
                                      transition_length=tl)
            truth = toy_point_labels(ramps, X.shape[0])
            core = (truth == TRANSITION).astype(float)
            name = f"toy_s{sigma}_tl{tl}"
            panels, summ, comp = process(name, X, TOY_W, TOY_Q, args.R,
                                         truth=truth, core=core)
            plot_dataset(name, X, panels, 0, min(4000, X.shape[0]), figdir)
            all_summary += summ
            all_comp.append(comp)

    if "langevin" in args.datasets:
        X = np.loadtxt(os.path.join(REPO_ROOT, "data", "Langevin",
                                    "langevin.txt")).ravel()
        truth = langevin_point_labels(X, 0.0)
        core = (np.abs(X) < 0.4).astype(float)
        panels, summ, comp = process("langevin", X, LANG_W, LANG_Q, args.R,
                                     truth=truth, core=core)
        plot_dataset("langevin", X, panels, 0, 20000, figdir)
        all_summary += summ
        all_comp.append(comp)

    if "prinz" in args.datasets:
        p = os.path.join(REPO_ROOT, "data", "prinz", "prinz.txt")
        X = np.loadtxt(p).ravel()
        panels, summ, comp = process("prinz", X, PRINZ_W, PRINZ_Q, args.R)
        plot_dataset("prinz", X, panels, 0, X.shape[0], figdir)
        all_summary += summ
        all_comp.append(comp)

    pd.DataFrame(all_summary).to_csv(
        os.path.join(RESULT_DIR, "summary.csv"), index=False)
    pd.concat(all_comp, ignore_index=True).to_csv(
        os.path.join(RESULT_DIR, "cluster_composition.csv"), index=False)
    print(f"\nwrote {RESULT_DIR}/summary.csv and cluster_composition.csv")


if __name__ == "__main__":
    main()
