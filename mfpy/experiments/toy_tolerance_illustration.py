"""
Generate Figure 8: What a matching tolerance means -- nested windows around one
true change point, for short vs. long ramps.

This figure illustrates the tolerance concept: how predictions at different
distances from the true change point would score under different tau values.

Generated by: toy_tolerance_illustration.py
"""

import os
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


def load_trajectory(path):
    """Load trajectory data from file."""
    return np.loadtxt(path)


def load_ground_truth_simple(gt_path):
    """Load ground truth change points (simplified version of toy_scoring.load_ground_truth)."""
    gt = np.loadtxt(gt_path).astype(int)
    if gt.ndim == 0:
        gt = gt.reshape(1)
    
    starts = gt[1:-1:2]
    ends = gt[2::2]
    n = min(len(starts), len(ends))
    ramps = np.stack([starts[:n], ends[:n]], axis=1)
    return ramps


def main():
    REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
    data_dir = os.path.join(REPO_ROOT, "data", "Toy_Model_Trajectories")
    fig_dir = os.path.join(REPO_ROOT, "results", "toy_sweep", "figures")
    os.makedirs(fig_dir, exist_ok=True)

    # Load the two example trajectories from the memo
    # Short ramp: sigma=5, transition_length=20
    traj_short = load_trajectory(os.path.join(data_dir, "sigma_5_transition_20.txt"))
    ramps_short = load_ground_truth_simple(
        os.path.join(data_dir, "sigma_5_transition_20_GroundTruth.txt")
    )

    # Long ramp: sigma=5, transition_length=50
    traj_long = load_trajectory(os.path.join(data_dir, "sigma_5_transition_50.txt"))
    ramps_long = load_ground_truth_simple(
        os.path.join(data_dir, "sigma_5_transition_50_GroundTruth.txt")
    )

    # For illustration, use ramp 5 (index 4, since 0-indexed)
    ramp_idx = 4  # ramp 5

    fig, axes = plt.subplots(2, 1, figsize=(12, 6))

    # ====== TOP: SHORT RAMP ======
    ax = axes[0]

    ramp_start_short = int(ramps_short[ramp_idx, 0])
    ramp_end_short = int(ramps_short[ramp_idx, 1])

    # Show a window around the ramp start
    window_start = max(0, ramp_start_short - 100)
    window_end = min(len(traj_short), ramp_start_short + 200)
    t = np.arange(window_start, window_end)
    x = traj_short[window_start:window_end]

    ax.plot(t, x, 'k-', lw=1.5, label='trajectory')

    # True change point (ramp start)
    true_cp = ramp_start_short
    ax.axvline(true_cp, color='black', linestyle='-', lw=2.5, label='true change point')

    # Detected change point: offset +4
    detected_cp = true_cp + 4
    ax.axvline(detected_cp, color='darkred', linestyle='--', lw=1.8, alpha=0.7)
    ax.text(detected_cp, ax.get_ylim()[1] * 0.95, f'detected, offset +4',
            fontsize=9, ha='left', color='darkred', weight='bold')

    # Tolerance windows: τ = 5, 10, 25, 50
    taus = [5, 10, 25, 50]
    colors = ['#E8F4F8', '#B8D4D8', '#D4A574', '#C85A54']
    alphas = [0.5, 0.4, 0.3, 0.2]

    for tau, color, alpha in zip(taus, colors, alphas):
        ax.axvspan(true_cp - tau, true_cp + tau, alpha=alpha, color=color,
                   label=f'τ = {tau}')

    ax.set_xlim(window_start, window_end)
    ax.set_xlabel('t')
    ax.set_ylabel('x')
    ax.set_title(f'σ=5, ℓ=20, ramp 5 (start)', fontsize=11, weight='bold')
    ax.grid(alpha=0.3)
    ax.legend(loc='upper left', fontsize=8, ncol=2)

    # ====== BOTTOM: LONG RAMP ======
    ax = axes[1]

    ramp_start_long = int(ramps_long[ramp_idx, 0])
    ramp_end_long = int(ramps_long[ramp_idx, 1])

    # Show a window around the ramp start
    window_start = max(0, ramp_start_long - 100)
    window_end = min(len(traj_long), ramp_start_long + 250)
    t = np.arange(window_start, window_end)
    x = traj_long[window_start:window_end]

    ax.plot(t, x, 'k-', lw=1.5, label='trajectory')

    # True change point (ramp start)
    true_cp = ramp_start_long
    ax.axvline(true_cp, color='black', linestyle='-', lw=2.5, label='true change point')

    # Detected change point: offset +15
    detected_cp = true_cp + 15
    ax.axvline(detected_cp, color='darkred', linestyle='--', lw=1.8, alpha=0.7)
    ax.text(detected_cp, ax.get_ylim()[1] * 0.95, f'detected, offset +15',
            fontsize=9, ha='left', color='darkred', weight='bold')

    # Tolerance windows
    for tau, color, alpha in zip(taus, colors, alphas):
        ax.axvspan(true_cp - tau, true_cp + tau, alpha=alpha, color=color,
                   label=f'τ = {tau}')

    ax.set_xlim(window_start, window_end)
    ax.set_xlabel('t')
    ax.set_ylabel('x')
    ax.set_title(f'σ=5, ℓ=50, ramp 5 (start)', fontsize=11, weight='bold')
    ax.grid(alpha=0.3)
    ax.legend(loc='upper left', fontsize=8, ncol=2)

    # Overall title
    fig.suptitle(
        'What a matching tolerance means: nested windows around one true\nchange point, '
        'short ramp (top) vs. long ramp (bottom)',
        fontsize=12, weight='bold', y=0.995
    )

    fig.tight_layout(rect=[0, 0, 1, 0.97])

    # Save
    for ext in ('pdf', 'png'):
        filepath = os.path.join(fig_dir, f'tolerance_illustration.{ext}')
        fig.savefig(filepath, dpi=200, bbox_inches='tight')
        print(f'Saved: {filepath}')

    plt.close(fig)


if __name__ == "__main__":
    main()
